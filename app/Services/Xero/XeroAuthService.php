<?php

namespace App\Services\Xero;

use Illuminate\Support\Facades\Cache;
use Illuminate\Support\Facades\Log;
use League\OAuth2\Client\Provider\GenericProvider;

class XeroAuthService
{
    private const TOKEN_CACHE_KEY   = 'xero_access_token';
    private const REFRESH_CACHE_KEY = 'xero_refresh_token';
    private const TENANT_CACHE_KEY  = 'xero_tenant_id';

    private const SCOPE = 'openid email profile offline_access accounting.invoices.read accounting.contacts.read accounting.settings.read accounting.attachments';

    private function getProvider(): GenericProvider
    {
        return new GenericProvider([
            'clientId'                => config('xero.client_id'),
            'clientSecret'            => config('xero.client_secret'),
            'redirectUri'             => config('xero.redirect_uri'),
            'urlAuthorize'            => 'https://login.xero.com/identity/connect/authorize',
            'urlAccessToken'          => 'https://identity.xero.com/connect/token',
            'urlResourceOwnerDetails' => 'https://api.xero.com/api.xro/2.0/Organisation',
        ]);
    }

    // ── Public API ─────────────────────────────────────────────────

    public function getAuthorizationUrl(): string
    {
        $provider = $this->getProvider();

        $authUrl = $provider->getAuthorizationUrl([
            'scope' => self::SCOPE,
        ]);

        // Save state generated by the provider
        Cache::put('xero_oauth_state', $provider->getState(), 600);

        Log::info('Xero Auth URL: ' . $authUrl);

        return $authUrl;
    }

    public function handleCallback(string $code, string $state): void
    {
        $savedState = Cache::pull('xero_oauth_state');

        if ($savedState !== $state) {
            throw new \RuntimeException('Xero OAuth: Invalid state parameter.');
        }

        $provider    = $this->getProvider();
        $accessToken = $provider->getAccessToken('authorization_code', [
            'code' => $code,
        ]);

        // Get tenant ID from Xero connections endpoint
        $tenantId = $this->fetchTenantId((string) $accessToken->getToken());

        // Store everything
        Cache::put(self::TOKEN_CACHE_KEY,   (string) $accessToken->getToken(),        $accessToken->getExpires() - time() - 60);
        Cache::put(self::REFRESH_CACHE_KEY, (string) $accessToken->getRefreshToken(), 60 * 24 * 60 * 60);
        Cache::put(self::TENANT_CACHE_KEY,  $tenantId,                                60 * 24 * 60 * 60);

        Log::info('Xero: Auth complete. Tenant: ' . $tenantId);
    }

    public function getAccessToken(): string
    {
        $token = Cache::get(self::TOKEN_CACHE_KEY);

        if ($token) {
            return $token;
        }

        $refreshToken = Cache::get(self::REFRESH_CACHE_KEY);

        if (!$refreshToken) {
            throw new \RuntimeException(
                'Xero: No access token available. Please visit /xero/connect to authorise.'
            );
        }

        return $this->refreshAccessToken($refreshToken);
    }

    public function getTenantId(): string
    {
        return Cache::get(self::TENANT_CACHE_KEY)
            ?? config('xero.tenant_id');
    }

    // ── Private helpers ────────────────────────────────────────────

    private function refreshAccessToken(string $refreshToken): string
    {
        Log::info('Xero: Refreshing access token.');

        $provider    = $this->getProvider();
        $accessToken = $provider->getAccessToken('refresh_token', [
            'refresh_token' => $refreshToken,
        ]);

        Cache::put(self::TOKEN_CACHE_KEY,   (string) $accessToken->getToken(),        $accessToken->getExpires() - time() - 60);
        Cache::put(self::REFRESH_CACHE_KEY, (string) $accessToken->getRefreshToken(), 60 * 24 * 60 * 60);

        return (string) $accessToken->getToken();
    }

    private function fetchTenantId(string $accessToken): string
    {
        // Use the Xero connections endpoint to get the tenant ID
        $response = \Illuminate\Support\Facades\Http::withHeaders([
            'Authorization' => 'Bearer ' . $accessToken,
            'Content-Type'  => 'application/json',
        ])->get('https://api.xero.com/connections');

        if ($response->failed()) {
            throw new \RuntimeException('Xero: Failed to fetch tenant ID: ' . $response->body());
        }

        $connections = $response->json();

        if (empty($connections)) {
            throw new \RuntimeException('Xero: No connections found. Make sure you select an organisation when authorising.');
        }

        return $connections[0]['tenantId'];
    }
}
